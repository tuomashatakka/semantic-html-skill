/** Tiny Markdown builders shared by the reference generator and the CLI. */

export const escapeCell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n+/g, " ").trim();

export function mdTable(head: readonly string[], rows: ReadonlyArray<readonly string[]>): string {
  if (!rows.length) return "";
  return [
    `| ${head.map(escapeCell).join(" | ")} |`,
    `| ${head.map(() => "---").join(" | ")} |`,
    ...rows.map((r) => `| ${head.map((_, i) => escapeCell(r[i] ?? "")).join(" | ")} |`),
  ].join("\n");
}

export const code = (s: string) => (s ? `\`${s}\`` : "");

export const tagList = (tags: readonly string[]) => (tags.length ? ` _(${tags.join(", ")})_` : "");

export const generatedHeader = (source: string) =>
  `<!-- GENERATED by src/build-references.ts from ${source} — do not edit by hand; run \`npm run build:refs\`. -->`;

export const anchor = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^\w\s-]/g, "")
    .trim()
    .replace(/\s+/g, "-");

/** Wrap bare `<tag>` mentions in backticks so they never render as HTML. */
export const codeTags = (s: string) => s.replace(/(^|[^`])(<\/?[a-z][\w-]*>)(?!`)/g, "$1`$2`");
